// Shared helpers and the registration entry point for the fprime-* checks.
#pragma once

#include "clang-tidy/ClangTidyCheck.h"
#include "clang-tidy/ClangTidyModule.h"
#include "clang/AST/ASTContext.h"
#include "clang/ASTMatchers/ASTMatchFinder.h"
#include "clang/ASTMatchers/ASTMatchers.h"
#include "clang/Lex/Lexer.h"
#include "llvm/ADT/StringRef.h"

#include <set>
#include <string>

namespace clang {
namespace tidy {
namespace fprime {

void registerFprimeChecks(ClangTidyCheckFactories &Factories);

// Spelling of the assertion macros CodeQL's FwAssert/Assertion classes recognise.
inline bool isAssertMacro(llvm::StringRef Name) { return Name == "FW_ASSERT" || Name == "assert"; }

// Function names CodeQL's FprimeBlocking.qll treats as interrupt service routines.
bool isIsrName(llvm::StringRef Name);
inline bool isSchedInHandler(llvm::StringRef Name) {
  return Name.contains("schedIn") && Name.endswith("_handler");
}
inline bool isFprimeHandler(llvm::StringRef Name) {
  return Name.endswith("_handler") || Name.endswith("_cmdHandler") || Name.endswith("_internalInterfaceHandler");
}
bool isIsrFunction(const FunctionDecl *F);

// Path classification mirroring the queries' getAbsolutePath().matches(...) filters.
bool inTestPath(llvm::StringRef Path);

// The expression FW_ASSERT(cond, ...) asserts: the condition of the outermost
// conditional operator generated by the macro, i.e. `cond` itself.
const Expr *assertedCondition(const Expr *MacroExpr);

// Source text of an expression (empty when it cannot be recovered).
std::string sourceText(const Expr *E, const ASTContext &Ctx);

// True when Loc is written in the main file or a header of the project (not a system header).
bool fromSource(SourceLocation Loc, const SourceManager &SM);

// Is `Use` dominated by a condition or assertion that reads variable `V`?
// Approximation of FprimeGuards.qll::guardedBefore within one function body.
bool guardedBefore(const VarDecl *V, const Stmt *Use, const FunctionDecl *F, ASTContext &Ctx);

} // namespace fprime
} // namespace tidy
} // namespace clang
